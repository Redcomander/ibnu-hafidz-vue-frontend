test('failed uploads show hosting diagnostics and preserve the selected APK for manual retry', async ({ page }) => {
 await setup(page); let attempts = 0
 await page.route('**/api/admin/app/releases', route => { attempts++; return route.fulfill({ status: 504, contentType: 'text/html', body: '<html>Gateway Timeout</html>' }) })
 await page.goto('/dashboard/mobile-app/releases')
 await expect(page.getByLabel('Berkas APK', { exact: true })).toBeEnabled()
 await page.getByLabel('Berkas APK', { exact: true }).setInputFiles({ name: 'release-13.apk', mimeType: 'application/vnd.android.package-archive', buffer: Buffer.from('apk') })
 await page.getByRole('button', { name: 'Unggah sebagai draft' }).click()
 const feedback = page.locator('.upload-error-card')
 await expect(feedback).toContainText('Hosting menghentikan atau kehabisan waktu unggah')
 await expect(feedback).toContainText('HTTP 504')
 await expect(feedback).toContainText('pastikan build belum tersimpan')
 await expect(page.getByText('release-13.apk', { exact: true })).toBeVisible()
 await expect(page.getByRole('button', { name: 'Unggah sebagai draft' })).toBeEnabled()
 await feedback.getByRole('button', { name: 'Muat ulang riwayat rilis' }).click()
 expect(attempts).toBe(1)
})
