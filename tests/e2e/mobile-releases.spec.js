test('APK upload remains draft and malformed file is rejected in the browser', async ({ page }) => {
 await setup(page); let uploads = 0
 await page.route('**/api/admin/app/releases', route => { uploads++; expect(route.request().method()).toBe('POST'); expect(route.request().headers()['content-type']).toContain('multipart/form-data'); return route.fulfill({ status: 201, json: release }) })
 await page.goto('/dashboard/mobile-app/releases')
 await expect(page.getByLabel('Berkas APK', { exact: true })).toBeEnabled()
 await page.getByLabel('Berkas APK', { exact: true }).setInputFiles({ name: 'wrong.txt', mimeType: 'text/plain', buffer: Buffer.from('bad') })
 await expect(page.getByRole('button', { name: 'Unggah sebagai draft' })).toBeDisabled(); expect(uploads).toBe(0)
 await page.getByLabel('Berkas APK').setInputFiles({ name: 'app.apk', mimeType: 'application/vnd.android.package-archive', buffer: Buffer.from('apk') })
 await page.getByRole('button', { name: 'Unggah sebagai draft' }).click()
 await expect.poll(() => uploads).toBe(1)
 await expect(page.getByText('APK tervalidasi dan disimpan sebagai draft. Belum dipublikasikan.')).toBeVisible()
})

test('release details and archive dialog support keyboard focus and explicit confirmation', async ({ page }) => {
 await setup(page); let archives = 0
 await page.route('**/api/admin/app/releases/1/archive', route => { archives++; return route.fulfill({ json: {} }) })
 await page.goto('/dashboard/mobile-app/releases')
 await page.getByRole('button', { name: 'Detail', exact: true }).click()
 const dialog = page.getByRole('dialog')
 await expect(dialog).toBeFocused()
 await dialog.getByText('Identitas & integritas APK').click()
 await expect(dialog.getByText('a'.repeat(64))).toBeVisible()
 await dialog.focus()
 await page.keyboard.press('Shift+Tab')
 await expect(dialog.getByRole('button', { name: 'Unduh APK' })).toBeFocused()
 await page.keyboard.press('Tab')
 await expect(dialog.getByRole('button', { name: 'Tutup dialog' })).toBeFocused()
 await page.keyboard.press('Escape')
 await expect(dialog).toHaveCount(0)
 await expect(page.getByRole('button', { name: 'Detail', exact: true })).toBeFocused()
 await page.getByRole('button', { name: 'Arsipkan', exact: true }).click()
 expect(archives).toBe(0)
 await expect(dialog.getByRole('heading', { name: 'Arsipkan v1.2.0?' })).toBeVisible()
 await dialog.getByRole('button', { name: 'Batal' }).click()
 expect(archives).toBe(0)
 await page.getByRole('button', { name: 'Arsipkan', exact: true }).click()
 await dialog.getByRole('button', { name: 'Konfirmasi arsip' }).click()
 await expect.poll(() => archives).toBe(1)
})

test('drag and drop validates APKs and selected files can be removed', async ({ page }) => {
 await setup(page); await page.goto('/dashboard/mobile-app/releases')
 const zone = page.getByRole('button', { name: 'Pilih APK atau seret ke sini' })
 await expect(zone).toHaveAttribute('aria-disabled', 'false')
 await zone.evaluate(el => {
  const transfer = new DataTransfer()
  transfer.items.add(new File(['apk'], 'release-13.apk', { type: 'application/vnd.android.package-archive' }))
  el.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: transfer }))
 })
 await expect(page.getByText('release-13.apk')).toBeVisible()
 await expect(page.getByRole('button', { name: 'Unggah sebagai draft' })).toBeEnabled()
 await page.getByRole('button', { name: 'Hapus pilihan' }).click()
 await expect(page.getByRole('button', { name: 'Unggah sebagai draft' })).toBeDisabled()
 await page.getByLabel('Berkas APK').setInputFiles({ name: 'too-large.apk', mimeType: 'application/vnd.android.package-archive', buffer: Buffer.alloc(100001) })
 await expect(page.getByRole('button', { name: 'Unggah sebagai draft' })).toBeDisabled()
})

